"""台词库：按场景类型分组的唯一台词，每句自带一对自洽的潜台词。

为什么要单独成库
----------------
v0 的台词库是「每个场景类型 3 句」，13 场戏共 45 行里只有 18 个不同文本，
同一场景类型的三场戏台词完全一样。这带来两个后果：

1. **统计上虚高**：行数看起来是 45，独立刺激只有 18 个。任何 MAE / 命中率的
   有效自由度都被高估约 2.5 倍。
2. **实验上可疑**：真实模型很可能在拟合这 18 句的具体措辞，
   而不是在学"台词线索 → 情绪"的映射。

扩库的原则
----------
不是随便多写几句，而是**按金标准线索表的桶来配平**。`reference.CUE_TABLE`
有 9 个桶（威胁 / 认错 / 挽留 / 表白安抚 / 隐忍 / 玩笑 / 惊喜 / 危机 / 质疑）
加一个默认桶，如果新库只往"危机""威胁"里堆，arousal 分布会跟着偏，
后面所有按 arousal 分层的分析都会失真。

所以每类场景的台词都刻意覆盖该场景**合理**的多个桶：冲突戏里有威胁、质疑、
认错、隐忍；独白里有质疑、认错、隐忍。同一句台词只属于一类场景，
避免跨场景类型重复（重复会让"场景类型"这个因子失效）。

潜台词为什么必须逐句配（2026-10-31 修）
------------------------------------
v1 的潜台词是从 8 个短语池里 `rng.choice` 随机抽的——结果「哇，这只猫好可爱」
配到了「表面平静，心里没底」，语义上完全不通。这不是措辞问题，是**金标污染**：
`reference.appraise()` 把潜台词当情绪线索读，随机抽到含「其实/心跳/怕」的短语
就给 arousal +1.2，18% 的行的金标被随机数改写，模型也因此收到了自相矛盾的输入
（用户标注时发现的）。

所以现在每句台词自带两条潜台词：

- `neutral`：描写表面行为，**不含**任何线索词（不触发 +1.2，也不触发任何桶）
- `tense`：同一行为的内部状态，**含**「其实/心跳/怕/紧张/忍住」之一（+1.2）

保留中性/紧张的对立是刻意的：它让 arousal 从 10 个取值变成约 20 个，
判读任务不再是"十选一"，MAE 才有分辨力。只是这个对立必须**语义成立**，
不能再靠随机抽。

设计约束（修改本文件时必须遵守）
--------------------------------
1. **台词里不能无意命中别的桶**。`appraise()` 按 CUE_TABLE 顺序取第一个命中，
   所以「我在」会先命中"表白/安抚"（6.2），「嗯」会先命中"隐忍"（4.0）。
   例如想写"平淡陈述"就不能让文本含「我在」「嗯」「血」「死」。
2. **neutral 潜台词必须干净**：不能含 心跳/其实/忍住/怕/紧张/犹豫，
   也不能含任何 CUE_TABLE 关键词——否则它会替台词决定金标。
3. **tense 潜台词必须含一个触发词**（其实/心跳/怕/紧张/忍住），
   且不能引入比台词所在桶更靠前的桶关键词，否则同样的劫持会发生。
4. **每个文本全局唯一**。近义但不相同的句子可接受，完全相同的文本不可。
5. 台词要像漫剧/影视里的口语句子，不要写成说明文——否则判读任务的难度不真实。

改完必须跑 `python check_lines.py` 验证桶分布、重复率与潜台词合法性。
"""

