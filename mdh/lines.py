# neutral：不含 appraise() 的加成分支关键词（心跳/其实/怕/紧张/忍住/犹豫），
#          所以只影响上下文描述，不改变金标准 arousal
# tense  ：含上述关键词，命中 CUE_TABLE 后 arousal +1.2；未命中任何桶时判为「忐忑」6.2
#
# 这个区分是刻意的：它让 arousal 的取值从 10 个变成约 20 个，
